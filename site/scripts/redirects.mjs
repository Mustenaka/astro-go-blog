// Post-build: writes dist/redirects.map in Nginx `map` format, one line per legacy URL:
//   /old/path/ /new/path/;
// Sources: every post's `legacyUrls` (drafts skipped) plus the fixed table in
// src/legacy-redirects.json. A value of `410` means the old URL is gone.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFrontmatter } from '@astrojs/markdown-remark';

const siteDir = fileURLToPath(new URL('..', import.meta.url));
const postsDir = join(siteDir, '..', 'content', 'posts');
const distDir = join(siteDir, 'dist');
const fixed = JSON.parse(readFileSync(join(siteDir, 'src', 'legacy-redirects.json'), 'utf8'));

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) yield* walk(full);
    else if (name.endsWith('.mdx')) yield full;
  }
}

const entries = new Map();
for (const [from, to] of Object.entries(fixed)) {
  if (from.startsWith('_')) continue;
  entries.set(from, to);
}

let posts = 0;
for (const file of walk(postsDir)) {
  const { frontmatter } = parseFrontmatter(readFileSync(file, 'utf8'));
  if (frontmatter.draft === true) continue;
  const slug = file.replace(/\\/g, '/').split('/').pop().replace(/\.mdx$/, '');
  for (const legacy of frontmatter.legacyUrls ?? []) {
    if (entries.has(legacy) && entries.get(legacy) !== `/posts/${slug}/`) {
      console.warn(`[redirects] ${legacy} already mapped to ${entries.get(legacy)}, ignoring ${slug}`);
      continue;
    }
    entries.set(legacy, `/posts/${slug}/`);
    posts++;
  }
}

const lines = [
  '# Generated by site/scripts/redirects.mjs. Do not edit; edit legacyUrls in content/posts or src/legacy-redirects.json.',
  '# Usage in nginx: map $uri $legacy_redirect { include /path/to/redirects.map; default ""; }',
  '# A value of 410 means the old URL is gone: if ($legacy_redirect = 410) { return 410; }',
  ...[...entries.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([from, to]) => `${from} ${to};`),
];
writeFileSync(join(distDir, 'redirects.map'), lines.join('\n') + '\n');
console.log(`[redirects] wrote ${entries.size} mappings (${posts} from posts) to dist/redirects.map`);
